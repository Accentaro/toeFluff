/** Raw colour names from other mods and older palettes. Enmity and Kettu used PRIMARY_DARK_*; Discord renamed BRAND_NEW. */
export function renameRaw(key) {
	let m
	if ((m = key.match(/^PRIMARY_DARK_(\d+)$/))) return `PRIMARY_${m[1]}`
	if (key === 'PRIMARY_DARK') return 'PRIMARY_100'
	if ((m = key.match(/^BRAND_NEW_(\d+)$/))) return `BRAND_${m[1]}`
	if (key === 'BRAND_NEW') return 'BRAND_500'
	return null
}
